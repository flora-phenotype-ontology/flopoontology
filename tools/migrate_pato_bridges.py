#!/usr/bin/env python3
"""Re-point every FLOPO axiom and configuration row from a provisional FLOPO bridge quality to the
PATO identifier that PATO has since released (``config/flopo_pato_bridge_migration.tsv``).

The bridge classes themselves are not touched here: their builders
(``tools/build_flopo_botanical_extension_2.py`` for FLOPO_0985xxx and
``tools/build_flopo_growth_form_extension.py`` for FLOPO_0987xxx) read the same table and emit
an obsolete shell with ``IAO:0100001`` pointing at the PATO term. This script only rewrites
*references*:

- ``ontology/flopo.owl``: ``rdf:resource`` attributes (never ``rdf:about`` declarations);
- generated modules under ``ontology/`` that reference a bridge as a quality filler (the two
  builders' own modules are regenerated instead);
- configuration and rule tables whose quality column names a bridge.

Run it once, then rebuild the two bridge modules, the flora value rules, and the release passes.
"""

from __future__ import annotations

import argparse
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAPPING = Path("config/flopo_pato_bridge_migration.tsv")
OBO = "http://purl.obolibrary.org/obo/"
# Modules regenerated by their own builders from the mapping table.
REGENERATED = {"flopo-botanical-extension-2.ttl", "flopo-growth-form-extension.ttl"}
TABLES = [
    Path("config/valid_combinations.tsv"),
    Path("config/flopo_disjoint_values.tsv"),
    Path("config/flopo_flora_value_terms.tsv"),
    Path("config/flopo_automatic_eq_id_registry.tsv"),
    Path("flopo2/ingest/collenette_normalization.tsv"),
    Path("flopo2/ingest/ncvc_normalization.tsv"),
    Path("flopo2/ingest/llm_term_rules.tsv"),
    Path("flopo2/saudi/exclusive_values.tsv"),
]


def load_mapping(path: Path = MAPPING) -> dict[str, str]:
    with (ROOT / path).open(encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle, delimiter="\t"))
    mapping = {row["flopo_id"]: row["pato_id"] for row in rows}
    if len(mapping) != len(rows):
        raise ValueError("duplicate bridge identifier in the migration table")
    return mapping


def _replace_tokens(text: str, mapping: dict[str, str]) -> tuple[str, int]:
    count = 0
    for old, new in mapping.items():
        for sep in ("_", ":"):
            token = old.replace("_", sep, 1)
            replacement = new.replace("_", sep, 1)
            n = len(re.findall(rf"(?<![0-9A-Za-z_]){re.escape(token)}(?![0-9])", text))
            if n:
                text = re.sub(rf"(?<![0-9A-Za-z_]){re.escape(token)}(?![0-9])", replacement, text)
                count += n
    return text, count


def migrate_release(path: Path, mapping: dict[str, str]) -> int:
    text = path.read_text(encoding="utf-8")
    count = 0
    for old, new in mapping.items():
        pattern = f'rdf:resource="{OBO}{old}"'
        n = text.count(pattern)
        if n:
            text = text.replace(pattern, f'rdf:resource="{OBO}{new}"')
            count += n
    path.write_text(text, encoding="utf-8")
    return count


def migrate_module(path: Path, mapping: dict[str, str]) -> int:
    text = path.read_text(encoding="utf-8")
    for old in mapping:
        if re.search(rf"^obo:{old}\s+a\s+owl:Class", text, re.M) or re.search(rf"^<{OBO}{old}>\s+a\s+owl:Class", text, re.M):
            raise ValueError(f"{path.name} declares bridge class {old}; regenerate it with its builder instead")
    text, count = _replace_tokens(text, mapping)
    if count:
        path.write_text(text, encoding="utf-8")
    return count


def migrate_table(path: Path, mapping: dict[str, str]) -> int:
    text = path.read_text(encoding="utf-8")
    text, count = _replace_tokens(text, mapping)
    if path.name == "valid_combinations.tsv" and count:
        # Re-pointing can produce a row identical to an existing (bearer, PATO) pair: keep the first.
        lines = text.splitlines()
        seen, kept = set(), [lines[0]]
        for line in lines[1:]:
            key = tuple(line.split("\t")[:2])
            if key in seen:
                continue
            seen.add(key)
            kept.append(line)
        text = "\n".join(kept) + "\n"
    if count:
        path.write_text(text, encoding="utf-8")
    return count


CORPORA_SKIP = {"releases", "rdf"}   # published atlas releases and the RDF they were built from


def migrate_local_corpora(mapping: dict[str, str], root: Path = ROOT / "local-corpora") -> dict[str, int]:
    """Re-point bridge identifiers in every cache and derived file under ``local-corpora/``.

    The pipelines' LLM caches (``llm-*.jsonl``, ``llm-term-decisions.jsonl``), per-flora rule tables and
    annotated corpora keep the identifiers the model chose; after the bridges were obsoleted those
    choices are still right under the PATO identifiers. Atlas releases are immutable and skipped.
    """
    report: dict[str, int] = {}
    for path in sorted(root.rglob("*")):
        if not path.is_file() or path.suffix not in {".jsonl", ".tsv", ".json"}:
            continue
        if CORPORA_SKIP & set(path.relative_to(root).parts[:-1]):
            continue
        data = path.read_bytes()
        if not any(old.encode() in data or old.replace("_", ":", 1).encode() in data for old in mapping):
            continue   # source tables and other files that never name a bridge (some are not UTF-8)
        text, count = _replace_tokens(data.decode("utf-8"), mapping)
        if count:
            path.write_text(text, encoding="utf-8")
            report[str(path.relative_to(ROOT))] = count
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--mapping", type=Path, default=MAPPING)
    parser.add_argument("--release", type=Path, default=Path("ontology/flopo.owl"))
    parser.add_argument("--local-corpora", action="store_true",
                        help="only re-point the git-ignored caches and derived corpora under local-corpora/ "
                             "(LLM decision caches, term rules, annotated corpora, dispositions)")
    args = parser.parse_args()
    mapping = load_mapping(args.mapping)
    if args.local_corpora:
        for path in sorted(migrate_local_corpora(mapping).items()):
            print(f"{path[0]}\t{path[1]}")
        return
    report = {"release_references": migrate_release(ROOT / args.release, mapping)}
    for module in sorted((ROOT / "ontology").glob("*.ttl")):
        if module.name in REGENERATED:
            continue
        n = migrate_module(module, mapping)
        if n:
            report[module.name] = n
    for table in TABLES:
        n = migrate_table(ROOT / table, mapping)
        if n:
            report[str(table)] = n
    for key, value in report.items():
        print(f"{key}\t{value}")


if __name__ == "__main__":
    main()
