#!/usr/bin/env python3
"""Build ``ontology/flopo-bearer-axioms.ofn``: what follows for the plant from each phenotype.

A FLOPO phenotype class is a phene, a quality of the plant (``flopo2/owl/phene.py``):

    P EquivalentTo: 'flora phenotype' and 'phenotype of' some Y

'phenotype of' (RO:0002201) is functional and the inverse of 'has phenotype' (RO:0002200), so a
plant that has the phenotype P has the defining property Y. A reasoner for OWL 2 EL (ELK) does
not read functional or inverse properties and does not draw that conclusion. This file states it,
once per phenotype class, in a form ELK reads (the *bearer axiom*):

    'has phenotype' some P  SubClassOf  Y

Every axiom is entailed by FLOPO; the file adds nothing for a reasoner that reads all of OWL 2
DL. Load it together with ``flopo.owl`` of the same version (it imports that version) when
classifying with ELK data of the form ``Taxon SubClassOf 'has phenotype' some P``: the taxon is
then classified under the defining properties of its phenotypes, and a taxon with incompatible
phenotypes becomes unsatisfiable. See ``docs/phene-consistency.md``.

Run after the final passes of a release (the file carries the version of ``flopo.owl``):

    python -m tools.build_flopo_phene_bearers [--release ontology/flopo.owl] [--out ontology/flopo-bearer-axioms.ofn]
"""

from __future__ import annotations

import argparse
from pathlib import Path

from rdflib import OWL, RDF, RDFS, BNode, Graph, Literal, URIRef
from rdflib.namespace import DCTERMS

from flopo2.owl import phene
from flopo2.owl.io import serialize_ontology

OBO = "http://purl.obolibrary.org/obo/"
FLOPO_ONTOLOGY = URIRef(OBO + "flopo.owl")
BRIDGE = URIRef(OBO + "flopo/flopo-bearer-axioms.owl")
OUTPUT = Path("ontology/flopo-bearer-axioms.ofn")
_ENTITY_TYPES = (OWL.Class, OWL.ObjectProperty, OWL.DatatypeProperty, RDFS.Datatype)


def _copy(source: Graph, target: Graph, node, copies: dict):
    """Copy a class expression into the target with nodes of its own; declare what it names."""

    if isinstance(node, URIRef):
        for kind in _ENTITY_TYPES:
            if (node, RDF.type, kind) in source:
                target.add((node, RDF.type, kind))
        return node
    if not isinstance(node, BNode):
        return node
    if node in copies:
        return copies[node]
    fresh = copies[node] = BNode()
    for predicate, value in source.predicate_objects(node):
        target.add((fresh, predicate, _copy(source, target, value, copies)))
    return fresh


def build(release: Path) -> tuple[Graph, dict]:
    source = Graph().parse(release.as_posix())
    version = source.value(FLOPO_ONTOLOGY, OWL.versionInfo)
    if version is None:
        raise ValueError("the release has no owl:versionInfo")
    version = str(version)
    graph = Graph()
    graph.bind("obo", OBO)
    graph.add((BRIDGE, RDF.type, OWL.Ontology))
    graph.add((BRIDGE, OWL.versionIRI, URIRef(f"{OBO}flopo/releases/{version}/flopo-bearer-axioms.ofn")))
    graph.add((BRIDGE, OWL.versionInfo, Literal(version)))
    graph.add((BRIDGE, OWL.imports, URIRef(f"{OBO}flopo/releases/{version}/flopo.owl")))
    graph.add((BRIDGE, DCTERMS.title, Literal("FLOPO bearer axioms: from a phenotype to the plant that has it (OWL 2 EL bridge)", lang="en")))
    graph.add((BRIDGE, DCTERMS.license, URIRef("https://creativecommons.org/publicdomain/zero/1.0/")))
    graph.add((BRIDGE, RDFS.comment, Literal(
        "Generated by tools/build_flopo_phene_bearers.py from flopo.owl of the same version. A FLOPO "
        "phenotype class P is defined as 'flora phenotype' and 'phenotype of' some Y, where Y is a "
        "property of the plant. 'phenotype of' (RO:0002201) is functional and the inverse of 'has "
        "phenotype' (RO:0002200), so a plant that has P has the property Y. Reasoners for OWL 2 EL, "
        "such as ELK, do not read functional and inverse properties. This file states the "
        "consequence once per class: 'has phenotype' some P SubClassOf Y. Every axiom here is "
        "entailed by flopo.owl; nothing is added for an OWL 2 DL reasoner. Use it with ELK and data "
        "of the form Taxon SubClassOf 'has phenotype' some P: the taxon is classified under the "
        "defining properties of its phenotypes, and a taxon whose phenotypes cannot hold of one "
        "plant is unsatisfiable. The axioms are in OWL 2 EL wherever the defining property is. "
        "Documentation: docs/phene-consistency.md in the FLOPO repository.", lang="en")))
    for prop, label in ((phene.HAS_PHENOTYPE, phene.HAS_PHENOTYPE_LABEL), (phene.PHENOTYPE_OF, phene.PHENOTYPE_OF_LABEL)):
        graph.add((prop, RDF.type, OWL.ObjectProperty))
        graph.add((prop, RDFS.label, Literal(label, lang="en")))
    classes = phene.phene_classes(source)
    axioms = 0
    for cls in sorted(classes):
        graph.add((cls, RDF.type, OWL.Class))
        for body in classes[cls]:
            bearer = BNode()
            graph.add((bearer, RDF.type, OWL.Restriction))
            graph.add((bearer, OWL.onProperty, phene.HAS_PHENOTYPE))
            graph.add((bearer, OWL.someValuesFrom, cls))
            graph.add((bearer, RDFS.subClassOf, _copy(source, graph, body, {})))
            axioms += 1
    return graph, {"version": version, "classes": len(classes), "axioms": axioms}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--release", type=Path, default=Path("ontology/flopo.owl"))
    parser.add_argument("--out", type=Path, default=OUTPUT)
    args = parser.parse_args()
    graph, stats = build(args.release)
    serialize_ontology(graph, args.out, "ofn")
    print(f"{args.out}: version {stats['version']}, {stats['axioms']} bearer axioms of {stats['classes']} phenotype classes")


if __name__ == "__main__":
    main()
